#!/usr/bin/env python3
"""Regenerate marketplace_backend.did and the frontend declarations built from it.

basilisk 0.15.1 writes its Candid file to $CANISTER_CANDID_PATH on every build, and it declares every
type it finds anywhere under src/ (700-odd), not only the ones the service uses. Building straight onto
the committed file therefore bloats it. This builds onto a scratch file instead, keeps the service and
the types reachable from it, and has `dfx generate` refresh src/declarations/marketplace_backend.

Run it with the marketplace's own environment, the one release.yml builds in:

    python3 -m venv /tmp/marketplace-venv
    /tmp/marketplace-venv/bin/pip install -r src/marketplace_backend/requirements.txt
    /tmp/marketplace-venv/bin/python scripts/marketplace_candid.py
"""

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DID = ROOT / "src" / "marketplace_backend" / "marketplace_backend.did"
HEADER = (
    "// Generated by scripts/marketplace_candid.py. Do not edit by hand, and do not commit a build's output:\n"
    "// a build writes every type it finds under src/ onto this file. To regenerate it and its declarations:\n"
    "//   /tmp/marketplace-venv/bin/python scripts/marketplace_candid.py\n"
    "// (the script's docstring shows how to create that venv)\n"
)
# basilisk writes one `type Name = body;` per line
TYPE_LINE = re.compile(r"^type (\w+) = (.*);$")


def type_definitions(did: str) -> dict[str, str]:
    return {m[1]: m[2] for line in did.splitlines() if (m := TYPE_LINE.match(line))}


def service_of(did: str) -> str:
    return did[did.index("\nservice ") :]


def service_methods(did: str) -> list[str]:
    return re.findall(r'^\s*"([^"]+)" :', service_of(did), re.M)


def referenced_types(text: str, known: dict[str, str]) -> set[str]:
    """The declared types `text` names. A name followed by a colon is a field or variant case, not a type."""
    without_strings = re.sub(r'"[^"]*"', "", text)
    return {
        n
        for n in re.findall(r"\b([A-Za-z_]\w*)\b(?!\s*:)", without_strings)
        if n in known
    }


def reachable_types(did: str) -> set[str]:
    types = type_definitions(did)
    reached: set[str] = set()
    pending = referenced_types(service_of(did), types)
    while pending:
        name = pending.pop()
        if name not in reached:
            reached.add(name)
            pending |= referenced_types(types[name], types)
    return reached


def prune(did: str) -> str:
    keep = reachable_types(did)
    lines = [
        line
        for line in did.splitlines()
        if not (m := TYPE_LINE.match(line)) or m[1] in keep
    ]
    return "\n".join(lines) + "\n"


def build_did() -> str:
    with tempfile.TemporaryDirectory() as scratch:
        generated = Path(scratch) / "marketplace_backend.did"
        subprocess.run(
            [
                sys.executable,
                "-m",
                "basilisk",
                "marketplace_backend",
                "src/marketplace_backend/main.py",
            ],
            cwd=ROOT,
            env={**os.environ, "CANISTER_CANDID_PATH": str(generated)},
            check=True,
        )
        return generated.read_text()


def main() -> None:
    DID.write_text(HEADER + prune(build_did()))
    subprocess.run(["dfx", "generate", "marketplace_backend"], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
