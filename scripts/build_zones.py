#!/usr/bin/env python3
"""Generate src/realm_backend/zonedata, the IANA time zones a realm release bundles (realms-gos#511).

A realm keeps the zone file of its own ``Realm.timezone`` and nothing else, but any realm may set any zone, so every
release carries the tz database: one module per distinct zone file, loaded only when a realm uses that zone, with the
file as hex text that ``bytes.fromhex`` turns into raw bytes (``base64`` costs 17M instructions in a canister for a
few KB, ``fromhex`` nothing). Names that share a zone file (the tz database's links) share a module.

Run it before a release, with a newer tz database, to refresh the rules:

    python3 scripts/build_zones.py                       # from /usr/share/zoneinfo/tzdata.zi, needs zic
    python3 scripts/build_zones.py --source tzdata.zi    # from the zic source of another release
    python3 scripts/build_zones.py --check               # fail if the package is not what that source gives

The names are those GGG accepts for ``Realm.timezone`` (ggg I-ADM-4): ``Area/Location``, with ``Area`` one of the
tz database's. ``UTC`` needs no data. The zone files are compiled with ``zic -b slim``: the transitions up to the last
change of rule, and the POSIX TZ string at the end of the file for the years after.
"""

import argparse
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "realm_backend" / "zonedata"
AREAS = ("Africa", "America", "Antarctica", "Arctic", "Asia", "Atlantic", "Australia", "Europe", "Indian", "Pacific", "Etc")
DEFAULT_SOURCE = "/usr/share/zoneinfo/tzdata.zi"


def names_of(source):
    """``(version, names)``: the tz database's release, and every zone or link name GGG accepts."""
    lines = pathlib.Path(source).read_text().splitlines()
    version = lines[0].removeprefix("# version ")
    names = {line.split()[2 if line[0] == "L" else 1] for line in lines if line[:2] in ("Z ", "L ")}
    return version, sorted(n for n in names if n.partition("/")[0] in AREAS and "/" in n)


def zone_files(source, names):
    """The slim zone file of each name, compiled by zic."""
    with tempfile.TemporaryDirectory() as out:
        subprocess.run(["zic", "-b", "slim", "-d", out, str(source)], check=True)
        return {name: (pathlib.Path(out) / name).read_bytes() for name in names}


def module_name(name):
    """A module name for a zone name; ``+`` is the only character that would make two names collide."""
    return name.lower().replace("/", "_").replace("-", "_").replace("+", "_plus_")


def generate(source):
    """``{file name: text}`` of the package for the tz database at ``source``."""
    version, names = names_of(source)
    by_content = {}
    for name, data in zone_files(source, names).items():
        by_content.setdefault(data, []).append(name)
    modules = {names[0]: (module_name(names[0]), data) for data, names in by_content.items()}
    assert len({m for m, _ in modules.values()}) == len(modules), "two zones would share a module name"
    where = {n: modules[names[0]][0] for names in by_content.values() for n in names}
    files = {f"{module}.py": f'"""{first}"""\nDATA = bytes.fromhex("{data.hex()}")\n'
             for first, (module, data) in sorted(modules.items())}
    files["__init__.py"] = (
        f'"""The IANA time zones of release {version}, generated by scripts/build_zones.py: do not edit.\n\n'
        f"``MODULE`` maps each zone name to the module that holds its zone file in ``DATA``; core.zones reads one on\n"
        f'demand. ``_bundle`` makes the bundler ship all of them."""\n\n'
        f'VERSION = "{version}"\nMODULE = {{\n' + "".join(f'    "{n}": "{m}",\n' for n, m in sorted(where.items())) + "}\n")
    files["_bundle.py"] = (
        '"""Imports every zone module, so the bundler ships them. Nothing runs this: a module loads when it is read."""\n\n'
        + "".join(f"import zonedata.{m}  # noqa: F401\n" for m in sorted(set(where.values()))))
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--source", default=DEFAULT_SOURCE, help="a tz database in zic's compact form (tzdata.zi)")
    parser.add_argument("--check", action="store_true", help="fail if the package is out of date")
    args = parser.parse_args()
    files = generate(args.source)
    current = {p.name: p.read_text() for p in PACKAGE.glob("*.py")} if PACKAGE.exists() else {}
    if args.check:
        stale = sorted(n for n in files.keys() | current.keys() if files.get(n) != current.get(n))
        sys.exit(f"out of date: {', '.join(stale[:10])}{' ...' if len(stale) > 10 else ''}" if stale else 0)
    PACKAGE.mkdir(exist_ok=True)
    for name in current.keys() - files.keys():
        (PACKAGE / name).unlink()
    for name, text in files.items():
        (PACKAGE / name).write_text(text)
    print(f"wrote {len(files)} files to {PACKAGE.relative_to(ROOT)}: {len(files) - 2} zone files for release "
          f"{files['__init__.py'].split(chr(10))[0].split('release ')[1].split(',')[0]}")


if __name__ == "__main__":
    main()
