#!/usr/bin/env python3
"""Generate src/realm_backend/main.py from the @op registry.

    python3 scripts/gen_main.py          # write main.py
    python3 scripts/gen_main.py --check  # exit 1 when it is out of date
"""

import ast
import pathlib
import sys

SRC = pathlib.Path(__file__).resolve().parent.parent / "src" / "realm_backend"

HEAD = '''# Generated by scripts/gen_main.py from the @op registry. Do not edit.
# Stubs name each op function: Basilisk loads modules lazily, so a bare import would not register them.
from basilisk import Async, StableBTreeMap, init, post_upgrade, query, text, update, void
from ic_python_db import Database

__basilisk_features__ = ["shell", "browse"]

Database.init(db_storage=StableBTreeMap[str, str](memory_id=1, max_key_size=256, max_value_size=100_000))

{imports}
from op import dispatch, run  # noqa: E402


@init
def init_() -> void:
    setup.start()


@post_upgrade
def post_upgrade_() -> void:
    setup.start()

'''


def registry():
    ops = {}
    for path in sorted(SRC.glob("*.py")):
        if path.stem in ("main", "op"):
            continue
        for node in ast.parse(path.read_text()).body:
            for dec in getattr(node, "decorator_list", []):
                if isinstance(dec, ast.Call) and getattr(dec.func, "id", "") == "op":
                    read = any(k.arg == "read" and getattr(k.value, "value", False) for k in dec.keywords)
                    ops[node.name] = (read, path.stem)
    return dict(sorted(ops.items()))


def render():
    ops = registry()
    modules = sorted({m for _, m in ops.values()} | {"setup"})
    imports = "\n".join(f"import {m}  # noqa: E402,F401" for m in modules)
    stubs = "".join(
        f"\n@query\ndef {name}(args: text) -> text: return run(dispatch({module}.{name}, args))\n" if read else
        f"\n@update\ndef {name}(args: text) -> Async[text]: return (yield from dispatch({module}.{name}, args))\n"
        for name, (read, module) in ops.items())
    return HEAD.format(imports=imports) + stubs


def main():
    text, path = render(), SRC / "main.py"
    if "--check" not in sys.argv:
        path.write_text(text)
    elif not path.exists() or path.read_text() != text:
        sys.exit("src/realm_backend/main.py is out of date: run scripts/gen_main.py")


if __name__ == "__main__":
    main()
